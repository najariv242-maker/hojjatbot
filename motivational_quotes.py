def get_motivational_quote(index: int) -> Dict[str, str]:
    """Returns a structured morning quote dict by 0-based index."""
    clean_idx = index % len(MOTIVATIONAL_QUOTES)
    return MOTIVATIONAL_QUOTES[clean_idx]

def format_morning_message(student_name: str, quote_data: Dict[str, str]) -> str:
    """Formats the morning message in a warm, personal first-person tone addressing the student by name without 'دکتر هاشمی:'."""
    clean_name = (student_name or "دانش‌آموز").strip()
    author = quote_data.get("author", "سخن بزرگان")
    quote = quote_data.get("quote", "")
    coach_note = quote_data.get("coach_note", "چراغ هدف و رویاهاتو تو دل زنده نگه دار و امروز رو با قدرت شروع کن.")

    return (
        f"☀️ **سلام {clean_name} عزیز، صبح زیبات بخیر.** 🌱✨\n"
        "━━━━━━━━━━━━━━━━━━━━\n"
        f"🔥 **{author}:**\n"
        f"« {quote} »\n\n"
        "━━━━━━━━━━━━━━━━━━━━\n"
        f"**{clean_name}،** {coach_note}\n\n"
        "🎯 *پاشو، روز رو با اقتدار شروع کن؛ امروز مال توئه!* 🚀🎓"
    )
